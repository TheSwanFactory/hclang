/**
 * Regenerates the TypeScript embed of the Figures standard module.
 *
 * Every host serves a standard module from the program itself, never from the
 * filesystem: the CLI's root is a fresh temp directory, `HCLang` keeps an
 * in-memory root, and a browser has no files at all. A raw text import would
 * carry the bytes under Deno, but neither dnt (the npm build) nor Vite (the
 * Fresh consumer of `@swanfactory/hcweb`) accepts one, so this script writes the
 * maintained source into a plain module that every bundler can carry.
 * `lib/modules/standard-modules.test.ts` compares the embed with the maintained
 * file through a text import and fails when they disagree.
 *
 * Usage: `deno task modules:embed`
 *
 * @module
 */

/** The maintained artifact, the only source of truth for the module. */
export const FIGURES_SOURCE_PATH = "lib/modules/figures.hc";

/** The generated module every host imports. */
export const FIGURES_EMBED_PATH = "lib/modules/figures-source.ts";

/**
 * Renders the embed as one string literal per source line, so a change to the
 * maintained file shows up as the same line-level change in the embed.
 *
 * @param source The maintained source, exactly as read.
 * @param from The repository path the source was read from.
 * @returns The TypeScript module text, before formatting.
 */
export function renderEmbed(source: string, from: string): string {
  const lines = source.split("\n").map((line) => `  ${JSON.stringify(line)},`);
  return [
    `// Generated by scripts/embed-modules.ts from ${from}. Do not edit.`,
    "// Regenerate with `deno task modules:embed`.",
    "",
    `/** The maintained source of \`${from}\`, joined from its lines. */`,
    "export const FIGURES_SOURCE: string = [",
    ...lines,
    '].join("\\n");',
    "",
  ].join("\n");
}

if (import.meta.main) {
  const source = await Deno.readTextFile(FIGURES_SOURCE_PATH);
  await Deno.writeTextFile(
    FIGURES_EMBED_PATH,
    renderEmbed(source, FIGURES_SOURCE_PATH),
  );
  // Format here, so the committed embed passes `deno fmt --check` unchanged.
  const formatted = await new Deno.Command(Deno.execPath(), {
    args: ["fmt", "--quiet", FIGURES_EMBED_PATH],
    stdin: "null",
  }).output();
  if (!formatted.success) {
    throw new Error(new TextDecoder().decode(formatted.stderr));
  }
  console.log(`Wrote ${FIGURES_EMBED_PATH} from ${FIGURES_SOURCE_PATH}`);
}
