/**
 * Regenerates the TypeScript embed of every standard module.
 *
 * Every `lib/modules/*.hc` is a standard module, served as
 * `'./modules/<file>'`, so adding one means adding the file and rerunning this
 * script. It reads only that directory, never `lib/` code, so it still runs
 * when the embed is stale or a module was just added.
 *
 * Every host serves a standard module from the program itself, never from the
 * filesystem: the CLI's root is a fresh temp directory, `HCLang` keeps an
 * in-memory root, and a browser has no files at all. Deno takes a raw text
 * import of the `.hc` file everywhere, but dnt (the npm build) refuses one and
 * Vite (the Fresh consumer of `@swanfactory/hcweb`) parses the imported file as
 * JavaScript, so this script writes the maintained sources into one plain
 * module that every bundler can carry.
 *
 * The embed is committed, and git is the drift check: `deno task modules:check`
 * regenerates it and fails on any difference. The pre-commit hook and
 * `test:all` both run that, so a stale embed never lands.
 *
 * Usage: `deno task modules:embed`
 *
 * @module
 */

/** The directory of maintained modules, the only source of truth for them. */
export const MODULES_DIR: URL = new URL("../lib/modules/", import.meta.url);

/** The generated module every host imports. */
export const EMBED_PATH: URL = new URL("standard-sources.ts", MODULES_DIR);

/** One maintained module: its file name in `MODULES_DIR` and its source. */
export type ModuleSource = { file: string; source: string };

/** A module file name that is already a canonical path segment. */
const MODULE_FILE = /^[A-Za-z0-9][A-Za-z0-9_-]*\.hc$/;

const HEADER = [
  "// Generated by scripts/embed-modules.ts from lib/modules/*.hc. Do not edit.",
  "// Regenerate with `deno task modules:embed`.",
];

/**
 * Selects the module files from a directory listing, in a stable order.
 *
 * A module's key must be canonical, or `ResourceMapStore` would throw when a
 * host starts, so a name that is not is refused here instead.
 *
 * @param names The file names in `MODULES_DIR`.
 * @returns The `.hc` names, sorted.
 */
export function moduleFiles(names: Iterable<string>): string[] {
  const files = [...names].filter((name) => name.endsWith(".hc"));
  const refused = files.filter((name) => !MODULE_FILE.test(name));
  if (refused.length > 0) {
    throw new Error(
      `standard module file names must match ${MODULE_FILE}: ${
        refused.join(", ")
      }`,
    );
  }
  return files.sort();
}

/**
 * The canonical, root-relative key a module is served under.
 *
 * @param file The module's file name in `MODULES_DIR`.
 * @returns The key `'./modules/<file>'` names.
 */
export function moduleKey(file: string): string {
  return `modules/${file}`;
}

/**
 * Renders the embed, each source as one string literal per line, so a change
 * to a maintained file shows up as the same line-level change in the embed.
 *
 * @param modules The maintained modules, each source exactly as read.
 * @returns The TypeScript module text, before formatting.
 */
export function renderEmbed(modules: readonly ModuleSource[]): string {
  const entries = modules.flatMap(({ file, source }) => [
    "  [",
    `    ${JSON.stringify(moduleKey(file))},`,
    "    [",
    ...source.split("\n").map((line) => `      ${JSON.stringify(line)},`),
    '    ].join("\\n"),',
    "  ],",
  ]);
  return [
    ...HEADER,
    "",
    "/**",
    " * The maintained source of every `lib/modules/*.hc`, by canonical key, each",
    " * joined from its lines.",
    " */",
    "export const STANDARD_SOURCES: ReadonlyMap<string, string> = new Map([",
    ...entries,
    "]);",
    "",
  ].join("\n");
}

/** Reads every maintained module, in the order the embed lists them. */
async function readModules(): Promise<ModuleSource[]> {
  const names: string[] = [];
  for await (const entry of Deno.readDir(MODULES_DIR)) {
    if (entry.isFile) names.push(entry.name);
  }
  const files = moduleFiles(names);
  if (files.length === 0) {
    throw new Error(`no standard modules (*.hc) found in ${MODULES_DIR}`);
  }
  const modules: ModuleSource[] = [];
  for (const file of files) {
    const source = await Deno.readTextFile(new URL(file, MODULES_DIR));
    modules.push({ file, source });
  }
  return modules;
}

if (import.meta.main) {
  if (Deno.args.length > 0) {
    throw new Error(`Unsupported argument(s): ${Deno.args.join(" ")}`);
  }
  const modules = await readModules();
  await Deno.writeTextFile(EMBED_PATH, renderEmbed(modules));
  console.log(
    `Wrote ${EMBED_PATH.pathname} from ${modules.length} module(s)`,
  );
}
