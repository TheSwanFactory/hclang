/**
 * Regenerates the TypeScript embed of the bundled HC files.
 *
 * Every `hc/*.hc` ships with the package, served as `'./hc/<file>'`, so adding
 * one means adding the file and rerunning this script. It reads only that
 * directory, never `lib/` code, so it still runs when the embed is stale or a
 * file was just added.
 *
 * Every host serves a bundled file from the program itself, never from the
 * filesystem: the CLI's root is a fresh temp directory, `HCLang` keeps an
 * in-memory root, and a browser has no files at all. Deno takes a raw text
 * import of the `.hc` file everywhere, but dnt (the npm build) refuses one and
 * Vite (the Fresh consumer of `@swanfactory/hcweb`) parses the imported file as
 * JavaScript, so this script writes the maintained sources into one plain
 * module that every bundler can carry.
 *
 * The embed is committed, and git is the drift check: `deno task bundle:check`
 * regenerates it and fails on any difference. The pre-commit hook and
 * `test:all` both run that, so a stale embed never lands.
 *
 * Usage: `deno task bundle:embed`
 *
 * @module
 */

/** The bundled HC files, the only source of truth for them. */
export const HC_DIR: URL = new URL("../hc/", import.meta.url);

/** The generated module every host imports. */
export const EMBED_PATH: URL = new URL(
  "../lib/bundle/hc-sources.ts",
  import.meta.url,
);

/** One bundled file: its name in `HC_DIR` and its source. */
export type HCSource = { file: string; source: string };

/** An HC file name that is already a canonical path segment. */
const HC_FILE = /^[A-Za-z0-9][A-Za-z0-9_-]*\.hc$/;

const HEADER = [
  "// Generated by scripts/embed-hc.ts from hc/*.hc. Do not edit.",
  "// Regenerate with `deno task bundle:embed`.",
];

/**
 * Selects the HC files from a directory listing, in a stable order.
 *
 * A file's key must be canonical, or `ResourceMapStore` would throw when a host
 * starts, so a name that is not is refused here instead.
 *
 * @param names The file names in `HC_DIR`.
 * @returns The `.hc` names, sorted.
 */
export function hcFiles(names: Iterable<string>): string[] {
  const files = [...names].filter((name) => name.endsWith(".hc"));
  const refused = files.filter((name) => !HC_FILE.test(name));
  if (refused.length > 0) {
    throw new Error(
      `bundled HC file names must match ${HC_FILE}: ${refused.join(", ")}`,
    );
  }
  return files.sort();
}

/**
 * The canonical, root-relative key a bundled file is served under.
 *
 * @param file The file's name in `HC_DIR`.
 * @returns The key `'./hc/<file>'` names.
 */
export function hcKey(file: string): string {
  return `hc/${file}`;
}

/**
 * Renders the embed, each source as one string literal per line, so a change
 * to a bundled file shows up as the same line-level change in the embed.
 *
 * @param sources The bundled files, each source exactly as read.
 * @returns The TypeScript module text, before formatting.
 */
export function renderEmbed(sources: readonly HCSource[]): string {
  const entries = sources.flatMap(({ file, source }) => [
    "  [",
    `    ${JSON.stringify(hcKey(file))},`,
    "    [",
    ...source.split("\n").map((line) => `      ${JSON.stringify(line)},`),
    '    ].join("\\n"),',
    "  ],",
  ]);
  return [
    ...HEADER,
    "",
    "/**",
    " * The source of every bundled `hc/*.hc`, by canonical key, each joined from",
    " * its lines.",
    " */",
    "export const HC_SOURCES: ReadonlyMap<string, string> = new Map([",
    ...entries,
    "]);",
    "",
  ].join("\n");
}

/** Reads every bundled file, in the order the embed lists them. */
async function readSources(): Promise<HCSource[]> {
  const names: string[] = [];
  for await (const entry of Deno.readDir(HC_DIR)) {
    if (entry.isFile) names.push(entry.name);
  }
  const files = hcFiles(names);
  if (files.length === 0) {
    throw new Error(`no HC files (*.hc) found in ${HC_DIR}`);
  }
  const sources: HCSource[] = [];
  for (const file of files) {
    const source = await Deno.readTextFile(new URL(file, HC_DIR));
    sources.push({ file, source });
  }
  return sources;
}

if (import.meta.main) {
  if (Deno.args.length > 0) {
    throw new Error(`Unsupported argument(s): ${Deno.args.join(" ")}`);
  }
  const sources = await readSources();
  await Deno.writeTextFile(EMBED_PATH, renderEmbed(sources));
  console.log(`Wrote ${EMBED_PATH.pathname} from ${sources.length} file(s)`);
}
