/**
 * Denum: the signed-load carrier of the binary Cayley–Dickson step ladder
 * (occurrence/figure 007.31, 007.32, 007.32b).
 *
 * This is the typed reference implementation. It depends on no Frame, so the
 * HC class in `hc/denum.hc` and the exhaustive tests can be checked against it.
 * A Denum is a constructed state, not a conventional number:
 *
 * - a retained application **Count** `C ∈ ℕ₀`;
 * - a nonempty ordered list of **loads**, each `W ∈ ℕ₀`, one per channel.
 *
 * There is no stored rank (occurrence/figure 007.35). The arity is `A =
 * loads.length`, positive and independent of the Count, and the rank is the
 * derived integer reading {@link rankOf}` = ⌊log₂ A⌋`. Any positive arity is a
 * representable Denum. Only the arities `1, 2, 4, 8, 16, 32` are Cayley–Dickson
 * ({@link isCD}); every CD-dependent operation refuses the others with
 * `$!.denum-unsupported-arity` rather than guess a signature law.
 *
 * On a CD arity, rank 0 has one unsigned channel `e_ε`. Rank `n ≥ 1` has `2ⁿ` channels, `±e_b`
 * for every direction `b` of `n − 1` bits. Channels are ordered positives
 * first, then negatives, each by direction value: channel `b` is `+e_b` and
 * channel `2ⁿ⁻¹ + b` is `−e_b`. A minus names a *signature*; a load is never
 * negative. The algebraic value is the signed observation {@link coordinates}, not the
 * Denum.
 *
 * The product of two signed signatures is
 * `(σ e_a)(ρ e_b) = σρ·τ(a, b) e_(a⊕b)`, where the twist `τ` is generated by
 * the Cayley–Dickson recurrence `(a,b)(c,d) = (ac − d̄b, da + bc̄)` in
 * {@link cdTwist}. No multiplication table is written by hand.
 *
 * Freshness: a Denum is a value. `loads` is only `readonly` in the type, not
 * frozen at runtime, so every operation here ({@link promote},
 * {@link opposite}, {@link conjugate}, {@link add}, {@link multiply}, ...)
 * answers a new object with its own `loads` array and never the argument or
 * an alias of its loads, even when the result equals the argument (same-rank
 * promotion, D0 conjugation). Callers must not mutate a Denum they are given.
 *
 * Count is carried, never derived from loads: `C(X+Y) = C(X)+C(Y)`,
 * `C(X⊗Y) = C(X)·C(Y)`, `C(Opp X) = C(X)` and promotion keeps it. These are
 * the explicit candidate laws of 007.32 §6, implemented for pure Denum
 * arithmetic only. They are not the application phase `C mod arity`, and
 * nothing here changes Demi.
 *
 * @module
 */

/** The highest rung implemented: D5, the sedenions, 32 channels. */
export const MAX_RANK = 5;

/** A Denum: retained application Count and one load per channel. */
export interface Denum {
  readonly count: bigint;
  readonly loads: readonly bigint[];
}

/** A failure of the Denum contract, named like an HC error. */
export class DenumError extends Error {
  constructor(public readonly kind: string, detail = "") {
    super(detail ? `${kind} ${detail}` : kind);
  }
}

/** The schema's display name, `CD[n]`. */
export function schemaName(rank: number): string {
  return `CD[${rank}]`;
}

/** Channel count of `CD[rank]`: 1 at rank 0, otherwise `2^rank`. */
export function arity(rank: number): number {
  checkRank(rank);
  return rank === 0 ? 1 : 2 ** rank;
}

/** Number of direction bits of a rank: `rank − 1`, or 0 at rank 0. */
export function directionBits(rank: number): number {
  checkRank(rank);
  return rank === 0 ? 0 : rank - 1;
}

function checkRank(rank: number): void {
  if (!Number.isInteger(rank) || rank < 0 || rank > MAX_RANK) {
    throw new DenumError("$!.denum-rank", String(rank));
  }
}

/**
 * The derived rank of a channel arity: `⌊log₂ A⌋`, the greatest `n` with
 * `2ⁿ ≤ A`, by integer arithmetic only (no floating-point logarithm). A is a
 * positive integer: 1→0, 2,3→1, 4..7→2, 8..15→3, 32..63→5, 64→6.
 *
 * @throws DenumError `$!!.invalid-denum` for a non-positive or non-integer A.
 */
export function rankOfArity(channels: number): number {
  if (!Number.isInteger(channels) || channels < 1) {
    throw new DenumError("$!!.invalid-denum", `arity ${channels}`);
  }
  let rank = 0;
  let threshold = 2;
  while (threshold <= channels) {
    rank++;
    threshold *= 2;
  }
  return rank;
}

/** The derived rank of a Denum, `⌊log₂ loads.length⌋`; never `count`. */
export function rankOf(source: Denum): number {
  return rankOfArity(source.loads.length);
}

/**
 * The one CD capability predicate: the arity is a power of two whose rung is
 * implemented, `A = 2ʳ` with `0 ≤ r ≤ MAX_RANK`. Rank alone is not enough:
 * A = 3 has rank 1 and A = 6 rank 2, and neither is a CD rung.
 */
export function isCDArity(channels: number): boolean {
  const rank = Number.isInteger(channels) && channels >= 1
    ? rankOfArity(channels)
    : -1;
  return rank >= 0 && rank <= MAX_RANK && channels === 2 ** rank;
}

/** True when the Denum's arity is a shipped Cayley–Dickson rung. */
export function isCD(source: Denum): boolean {
  return isCDArity(source.loads.length);
}

/**
 * The rank of a CD Denum, the guard at every CD-only entry point.
 *
 * @throws DenumError `$!.denum-unsupported-arity` for any other arity.
 */
export function cdRank(source: Denum): number {
  if (!isCD(source)) {
    throw new DenumError(
      "$!.denum-unsupported-arity",
      `${source.loads.length}`,
    );
  }
  return rankOf(source);
}

/**
 * The schema description of a Denum: `CD[n]` on a CD arity, otherwise
 * `Arity[A]`, which never claims a Cayley–Dickson rung.
 */
export function schemaOf(source: Denum): string {
  return isCD(source)
    ? schemaName(rankOf(source))
    : `Arity[${source.loads.length}]`;
}

/**
 * The Cayley–Dickson twist of two basis directions of `m` bits: the sign
 * `τ(x, y) ∈ {+1, −1}` with `e_x · e_y = τ(x, y) e_(x⊕y)` in the real algebra
 * of dimension `2^m`, generated by the doubling recurrence and conjugation
 * rather than by a table.
 *
 * Write `x = (x₁ x′)` with the top bit first. By
 * `(a,b)(c,d) = (ac − d̄b, da + bc̄)` and `conj(a,b) = (conj a, −b)`:
 *
 * - `(a,0)(c,0)`: `τ(x′, y′)`
 * - `(a,0)(0,d)`: `τ(y′, x′)`
 * - `(0,b)(c,0)`: `conj(y′)·τ(x′, y′)`
 * - `(0,b)(0,d)`: `−conj(y′)·τ(y′, x′)`
 *
 * where `conj(e_k)` contributes `+1` only for the scalar direction `k = 0`.
 */
export function cdTwist(x: number, y: number, m: number): 1 | -1 {
  if (m === 0) return 1;
  const half = 2 ** (m - 1);
  const xh = x >= half;
  const yh = y >= half;
  const x1 = xh ? x - half : x;
  const y1 = yh ? y - half : y;
  const conj = y1 === 0 ? 1 : -1;
  if (!xh && !yh) return cdTwist(x1, y1, m - 1);
  if (!xh && yh) return cdTwist(y1, x1, m - 1);
  if (xh && !yh) return (conj * cdTwist(x1, y1, m - 1)) as 1 | -1;
  return (-conj * cdTwist(y1, x1, m - 1)) as 1 | -1;
}

/** A signed signature of a rung: its sign and direction value. */
export interface Signature {
  readonly negative: boolean;
  readonly direction: number;
}

/** The signature a channel index names at `rank`. */
export function signatureOf(rank: number, channel: number): Signature {
  const size = arity(rank);
  if (!Number.isInteger(channel) || channel < 0 || channel >= size) {
    throw new DenumError("$!.denum-channel", String(channel));
  }
  if (rank === 0) return { negative: false, direction: 0 };
  const half = size / 2;
  return channel >= half
    ? { negative: true, direction: channel - half }
    : { negative: false, direction: channel };
}

/** The channel index of a signature at `rank`. */
export function channelOf(rank: number, signature: Signature): number {
  const size = arity(rank);
  if (rank === 0) {
    if (signature.negative || signature.direction !== 0) {
      throw new DenumError("$!.denum-signature", "D0 has only e_ε");
    }
    return 0;
  }
  const half = size / 2;
  if (
    !Number.isInteger(signature.direction) || signature.direction < 0 ||
    signature.direction >= half
  ) {
    throw new DenumError("$!.denum-signature", String(signature.direction));
  }
  return signature.negative ? half + signature.direction : signature.direction;
}

/** Native spelling of a signature: `e_ε` at D0, else `e_b` or `-e_b`. */
export function signatureName(rank: number, channel: number): string {
  const { negative, direction } = signatureOf(rank, channel);
  const bits = directionBits(rank);
  const label = bits === 0 ? "ε" : direction.toString(2).padStart(bits, "0");
  return `${negative ? "-" : ""}e_${label}`;
}

/** Parses `e_b`, `-e_b` or `e_ε` at `rank`; anything else is an error. */
export function parseSignature(rank: number, name: string): number {
  const match = /^(-?)e_([01]+|ε)$/.exec(name);
  if (!match) throw new DenumError("$!.denum-signature", name);
  const bits = directionBits(rank);
  const label = match[2];
  if (bits === 0) {
    if (label !== "ε") throw new DenumError("$!.denum-signature", name);
  } else if (label === "ε" || label.length !== bits) {
    throw new DenumError("$!.denum-signature", name);
  }
  if (rank === 0 && match[1] === "-") {
    throw new DenumError("$!.denum-signature", name);
  }
  return channelOf(rank, {
    negative: match[1] === "-",
    direction: bits === 0 ? 0 : parseInt(label, 2),
  });
}

/**
 * The signed product of two channels of the same rank: the destination channel
 * and nothing else is computed from the recurrence, never looked up.
 */
export function multiplyChannels(
  rank: number,
  left: number,
  right: number,
): number {
  if (rank === 0) return 0;
  const a = signatureOf(rank, left);
  const b = signatureOf(rank, right);
  const twist = cdTwist(a.direction, b.direction, directionBits(rank));
  const negative = (a.negative !== b.negative) !== (twist === -1);
  return channelOf(rank, { negative, direction: a.direction ^ b.direction });
}

function nonnegative(value: bigint, what: string): void {
  if (typeof value !== "bigint" || value < 0n) {
    throw new DenumError("$!!.invalid-denum", what);
  }
}

/**
 * Builds a Denum, refusing a negative Count or load or an empty load list.
 * Any positive arity is accepted; the loads are copied.
 */
export function denum(count: bigint, loads: readonly bigint[]): Denum {
  nonnegative(count, "count");
  if (loads.length < 1) {
    throw new DenumError("$!!.invalid-denum", "loads 0");
  }
  loads.forEach((load) => nonnegative(load, "load"));
  return { count, loads: [...loads] };
}

/** The zero-load CD Denum of a rank with a Count: present, unlike a missing host. */
export function zero(rank: number, count = 0n): Denum {
  return denum(count, Array(arity(rank)).fill(0n));
}

/**
 * Canonical old-summand embedding `Dn → D(n+1)`: `e_ε ↦ +e_ε` at D0 → D1, and
 * `±e_b ↦ ±e_(0b)` from D1 up, which is the same channel at the same sign with
 * a zero bit placed in front of the direction. Count and every load are kept;
 * the new channels start at zero.
 */
export function promote(source: Denum, rank: number): Denum {
  checkRank(rank);
  const from = cdRank(source);
  if (rank < from) {
    throw new DenumError("$!.denum-demotion", `${from} to ${rank}`);
  }
  // Always fresh: a same-rank promotion is a copy, never the argument itself.
  let current = {
    count: source.count,
    loads: [...source.loads],
  };
  for (let at = from; at < rank; at++) {
    const next = at + 1;
    const loads = Array<bigint>(arity(next)).fill(0n);
    for (let channel = 0; channel < current.loads.length; channel++) {
      const { negative, direction } = signatureOf(at, channel);
      // Leading zero bit leaves the direction value unchanged.
      loads[channelOf(next, { negative, direction })] = current.loads[channel];
    }
    current = { count: current.count, loads };
  }
  return current;
}

/** Both operands at the larger rank, by promotion. */
function align(left: Denum, right: Denum): [Denum, Denum, number] {
  const rank = Math.max(cdRank(left), cdRank(right));
  return [promote(left, rank), promote(right, rank), rank];
}

/**
 * Addition: corresponding loads add, opposite channels stay separate, and the
 * Counts add (C(X+Y) = C(X)+C(Y)).
 */
export function add(left: Denum, right: Denum): Denum {
  const [x, y] = align(left, right);
  return {
    count: x.count + y.count,
    loads: x.loads.map((load, channel) => load + y.loads[channel]),
  };
}

/**
 * Opposite: swaps the loads of `+e_b` and `−e_b`. D0 has no negative channel,
 * so it is promoted to D1 first. The Count is kept.
 */
export function opposite(source: Denum): Denum {
  const x = promote(source, Math.max(cdRank(source), 1));
  const half = x.loads.length / 2;
  return {
    count: x.count,
    loads: x.loads.map((_, channel) =>
      x.loads[channel < half ? channel + half : channel - half]
    ),
  };
}

/** Subtraction is addition of the opposite; it is observed, never erased. */
export function subtract(left: Denum, right: Denum): Denum {
  return add(left, opposite(right));
}

/**
 * Cayley–Dickson conjugation: scalar signatures `±e_0…0` are fixed and every
 * other signature goes to its opposite, `±e_b ↦ ∓e_b`. At D0 it is the
 * identity. Counts and loads are kept, only moved between channels.
 */
export function conjugate(source: Denum): Denum {
  if (cdRank(source) === 0) {
    return { count: source.count, loads: [...source.loads] };
  }
  const half = source.loads.length / 2;
  return {
    count: source.count,
    loads: source.loads.map((load, channel) => {
      const direction = channel % half;
      if (direction === 0) return load;
      return source.loads[channel < half ? channel + half : channel - half];
    }),
  };
}

/**
 * Ordered multiplication: every ordered pair of weighted signatures
 * contributes the product of its loads at the signed destination the
 * recurrence gives, and only identical full signatures aggregate. Operand
 * order and the caller's parenthesization are the caller's; nothing is
 * regrouped. Counts multiply (C(X⊗Y) = C(X)·C(Y)).
 */
export function multiply(left: Denum, right: Denum): Denum {
  const [x, y, rank] = align(left, right);
  const loads = Array<bigint>(arity(rank)).fill(0n);
  for (let i = 0; i < x.loads.length; i++) {
    if (x.loads[i] === 0n) continue;
    for (let j = 0; j < y.loads.length; j++) {
      if (y.loads[j] === 0n) continue;
      loads[multiplyChannels(rank, i, j)] += x.loads[i] * y.loads[j];
    }
  }
  return { count: x.count * y.count, loads };
}

/**
 * The Denum coordinates (occurrence/figure 007.32j, 007.33): an ordered list of
 * integers, one per direction `b`, read from the preserved state without
 * changing it. The one projection behind both HC spellings:
 *
 * - signed (`d.coordinates ()`): `S_b = W₍₊,b₎ − W₍₋,b₎`, the algebraic value;
 * - unsigned (`d.coordinates <>`): `U_b = W₍₊,b₎ + W₍₋,b₎`, the direction load
 *   with the ± signature forgotten (so `U ≠ |S|`).
 *
 * Width is 1 at D0 and `2ⁿ⁻¹` at Dn, n ≥ 1, in the direction order of
 * {@link signatureOf}. D0 has one unsigned channel `e_ε`, so both modes answer
 * `[W_ε]`. Count is neither used nor returned. Given the rank, the pair (S, U)
 * recovers the loads, `W₊ = (U+S)/2` and `W₋ = (U−S)/2`; Count, history and
 * the Denum itself are not recovered. Always a fresh array.
 */
export function coordinates(source: Denum, unsigned = false): bigint[] {
  if (cdRank(source) === 0) return [source.loads[0]];
  const half = source.loads.length / 2;
  return Array.from(
    { length: half },
    (_, b) =>
      unsigned
        ? source.loads[b] + source.loads[half + b]
        : source.loads[b] - source.loads[half + b],
  );
}

/**
 * The signed coordinates of v0.45.0.
 *
 * @deprecated Legacy compatibility alias of `coordinates(source)`, the signed
 * mode; `d.observe ()` in HC is its deprecated spelling. Use {@link coordinates}.
 */
export function observe(source: Denum): bigint[] {
  return coordinates(source);
}

/**
 * The declared residual of a Denum, the signed total `Σ W₊ − Σ W₋`. It is the
 * sum of the observed coordinates, so it is the existing residual `L − R` at
 * D1 and 0 at D0, which has no negative channel. A single integer, it forgets
 * the directions; it is an observer of the state, not the state.
 */
export function residual(source: Denum): bigint {
  return cdRank(source) === 0
    ? 0n
    : coordinates(source).reduce((a, b) => a + b, 0n);
}

/** True when every observed coordinate is zero. */
export function observesZero(source: Denum): boolean {
  return coordinates(source).every((coordinate) => coordinate === 0n);
}

/** True when no channel carries a load. */
export function isEmpty(source: Denum): boolean {
  return source.loads.every((load) => load === 0n);
}

/**
 * Host to Denum (the construction behind `X.#n`, distinct from promotion).
 *
 * A host answers only its Count `C`, Size `s` and residual `r`. Rank 0 keeps
 * the one load `s`. Rank `n ≥ 1` places `(s+r)/2` on `+e_0…0` and `(s−r)/2` on
 * `−e_0…0`, the two channels the existing fourth hash reads as left and right,
 * and every other channel starts at zero. A host's applications carry no
 * higher signature, so nothing is routed to them; `C mod arity` is the
 * application phase, not a signature rule. Count zero is the caller's nil.
 *
 * @throws DenumError `$!.denum-coherence` when the loads are not whole counts.
 */
export function fromHost(
  rank: number,
  count: bigint,
  size: bigint,
  residual: bigint,
): Denum {
  checkRank(rank);
  if (rank === 0) return denum(count, [size]);
  const sum = size + residual;
  const difference = size - residual;
  if (
    sum < 0n || difference < 0n || sum % 2n !== 0n || difference % 2n !== 0n
  ) {
    throw new DenumError("$!.denum-coherence");
  }
  const loads = Array<bigint>(arity(rank)).fill(0n);
  loads[0] = sum / 2n;
  loads[arity(rank) / 2] = difference / 2n;
  return denum(count, loads);
}

/** Text: `Denum(CD[2], C=7, W=[3, 2, 0, 1])` lists loads in channel order. */
export function denumText(source: Denum): string {
  return `Denum(${schemaOf(source)}, C=${source.count}, W=[${
    source.loads.join(", ")
  }])`;
}
